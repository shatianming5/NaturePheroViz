"""
e2e_pipeline.py — the TRUE end-to-end deployability test (AAAI convergent-critique fix).

All three independent reviewers (aris/claude R1-3, gpt-5.5, gemini-3.1-pro) named the SAME
ceiling: the 99%/0% detection is measured with the operator + params TEMPLATE-GIVEN. So the
"deployable goldless detector" claim was never tested end-to-end. This harness closes that gap:
given ONLY a messy, underspecified natural-language request over a real fixture — NOTHING
template-given — run the full pipeline and measure whether a silent error is caught:

  messy NL  --(1) LLM operator inference-->  op_hat
            --(2) LLM goldless contract synthesis (from the messy NL, no formula)-->  C
  C on wrong_fn(result) -> should FIRE      (recall)
  C on correct_fn + alts -> should PASS     (1 - FP)

Anti-circularity: the messy queries are generated by an LLM told to PARAPHRASE the high-level
goal into a rushed-analyst request, WITHOUT ever seeing the operator name, the formula, or the
slip to avoid; they are CACHED to messy_queries.json so a reviewer can audit exactly what the
system was fed. We report where loss occurs (operator inference vs contract synthesis) and the
full-system number (both must succeed) with 95% Wilson intervals.

Run: cd agent && LLM_API_BASE=.. LLM_API_KEY=.. python eval/e2e_pipeline.py --model gpt-5.4
"""
from __future__ import annotations
import argparse, json, math, re, sys, textwrap
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np  # noqa
import pandas as pd  # noqa
from eval.operator_expansion import CANDIDATES
from eval.w2_firing import _chat_api, classify_op_llm
from eval.autocontract_synth import (SYNTH_PROMPT, DELEAKED_INTENT, _schema, _result_schema,
                                     _run_auto, _as_frame, wilson, _parse_code)

# The messy-query generator sees ONLY the de-leaked high-level goal (already formula/keyword-
# free) and must paraphrase it into a rushed, underspecified analyst request. It never sees the
# operator id, the correct code, or the slip. This makes the NL strictly harder than the
# de-leaked intent, not easier.
MESSY_PROMPT = """You are a busy data analyst dashing off a quick request to a code assistant.
Rewrite the GOAL below as ONE short, natural, slightly underspecified request — the way a
hurried person actually types. STRICT RULES:
- Do NOT use any statistics jargon or operator name (no 'median', 'weighted', 'pooled',
  'cumulative', 'proportion', 'dedup', 'outer join', 'resample', etc.).
- Do NOT give any formula or spell out the exact computation.
- Do NOT say "not the X" / warn about any specific mistake.
- You MAY add a little realistic context or mild vagueness, but keep the core goal recoverable
  by a competent analyst.
Return ONLY the request text (one or two sentences), no preamble.

GOAL: {goal}
Columns available: {cols}."""


def gen_messy(goal, cols, model):
    out = _chat_api([{"role": "user", "content": MESSY_PROMPT.format(goal=goal, cols=cols)}],
                    model, max_tok=400)
    q = (out or "").strip().strip('"').strip()
    return q.split("\n")[0].strip() if q else goal


def synth_from_text(cand, intent_text, model):
    inp = cand.fixture()
    cols, extra = _schema(inp)
    kind, rcols = _result_schema(cand.correct_fn(inp))
    prompt = SYNTH_PROMPT.format(intent=intent_text, cols=cols, extra=extra,
                                 params=cand.params, kind=kind, rcols=rcols)
    # reasoning-heavy models (opus/sonnet) sometimes spend the whole budget "thinking" and emit
    # empty content on a long structured prompt. Retry with a terse directive + bigger budget.
    for attempt in range(3):
        p = prompt if attempt == 0 else (
            prompt + "\n\nIMPORTANT: output ONLY the JSON object now, no analysis or explanation.")
        out = _chat_api([{"role": "user", "content": p}], model, max_tok=4000 + attempt * 8000)
        code = _parse_code(out)
        if code:
            return code
    return None


def evaluate(cand, code):
    inp = cand.fixture()
    wrong = _as_frame(cand.wrong_fn(inp))
    correct = _as_frame(cand.correct_fn(inp))
    fw = _run_auto(code, inp, cand.params, wrong)
    pc = _run_auto(code, inp, cand.params, correct)
    alt_ok = True
    for alt in (cand.alt_correct_fns or []):
        try:
            a = _as_frame(alt(inp))
        except Exception:
            continue
        if _run_auto(code, inp, cand.params, a):
            alt_ok = False
    core = (fw is True) and (pc is False)
    full = core and alt_ok
    return {"fire_wrong": fw, "pass_correct": (pc is False), "alt_ok": alt_ok,
            "core": bool(core), "full": bool(full),
            "exec_ok": (fw is not None and pc is not None)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="gpt-5.4")
    ap.add_argument("--gen-model", default=None, help="model to WRITE messy queries (default=--model)")
    ap.add_argument("--cache", default="eval/results_e2e/messy_queries.json")
    ap.add_argument("--out", default="eval/results_e2e/e2e_report.json")
    ap.add_argument("--refresh-queries", action="store_true", help="regenerate cached messy NL")
    a = ap.parse_args()
    gen_model = a.gen_model or a.model

    from eval.core_candidates import CORE_CANDIDATES
    pool = list(CORE_CANDIDATES) + list(CANDIDATES)
    cands = [c for c in pool if isinstance(c.fixture().get("df"), pd.DataFrame)]

    cache_p = Path(a.cache)
    cache = json.load(open(cache_p)) if (cache_p.exists() and not a.refresh_queries) else {}
    changed = False
    for c in cands:
        if c.operator not in cache:
            goal = DELEAKED_INTENT.get(c.operator, f"Compute the {c.operator} transform.")
            cols, _ = _schema(c.fixture())
            cache[c.operator] = gen_messy(goal, cols, gen_model)
            changed = True
            print(f"  [gen] {c.operator:26} -> {cache[c.operator][:80]}", flush=True)
    if changed:
        cache_p.parent.mkdir(parents=True, exist_ok=True)
        json.dump(cache, open(cache_p, "w"), indent=2)

    recs = []
    n = op_ok = c_core = c_full = sys_core = exec_ok = 0
    for c in cands:
        msg = cache[c.operator]
        cols, _ = _schema(c.fixture())
        op_hat = classify_op_llm(msg, cols, a.model, conservative=False)
        code = synth_from_text(c, msg, a.model)
        ev = evaluate(c, code)
        op_correct = (op_hat == c.operator)
        system_ok = op_correct and ev["core"]        # BOTH inference and synthesis must work
        n += 1
        op_ok += int(op_correct); c_core += int(ev["core"]); c_full += int(ev["full"])
        sys_core += int(system_ok); exec_ok += int(ev["exec_ok"])
        recs.append({"op": c.operator, "messy_nl": msg, "op_hat": op_hat,
                     "op_correct": op_correct, **ev, "system_ok": system_ok})
        print(f"  {c.operator:26} op_hat={str(op_hat):22} {'OKop' if op_correct else 'xop':5} "
              f"contract:{'CORE' if ev['core'] else 'fail':4} => {'SYSTEM-OK' if system_ok else '-'}",
              flush=True)

    summary = {
        "model": a.model, "gen_model": gen_model, "n": n,
        "operator_inference": {"k": op_ok, "n": n, "pct_ci": wilson(op_ok, n)},
        "contract_synth_core": {"k": c_core, "n": n, "pct_ci": wilson(c_core, n)},
        "contract_synth_full": {"k": c_full, "n": n, "pct_ci": wilson(c_full, n)},
        "FULL_SYSTEM_core": {"k": sys_core, "n": n, "pct_ci": wilson(sys_core, n)},
        "exec_ok": exec_ok, "cases": recs,
    }
    outp = Path(a.out); outp.parent.mkdir(parents=True, exist_ok=True)
    json.dump(summary, open(outp, "w"), indent=2)
    print(f"\n=== END-TO-END from MESSY NL (nothing template-given, model {a.model}) ===")
    print(f"(1) operator inference:        {op_ok}/{n} = {wilson(op_ok,n)[0]}% CI{wilson(op_ok,n)[1:]}")
    print(f"(2) contract synth CORE:       {c_core}/{n} = {wilson(c_core,n)[0]}% CI{wilson(c_core,n)[1:]}")
    print(f"(2) contract synth FULL:       {c_full}/{n} = {wilson(c_full,n)[0]}% CI{wilson(c_full,n)[1:]}")
    print(f"FULL SYSTEM (op AND contract): {sys_core}/{n} = {wilson(sys_core,n)[0]}% CI{wilson(sys_core,n)[1:]}")
    print(f"exec-ok: {exec_ok}/{n}  -> {outp}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
